/**
 * 가이드 글 목록.
 *
 * 항목 페이지는 "○○이 얼마인가"에만 답한다. 그런데
 * 사람들이 실제로 치는 말은 그것과 다르다. 네이버 자동완성을 보면 이렇다.
 *
 *   비급여 뜻 · 급여 비급여 차이 · 비급여 조회 · 비급여 진료비 조회
 *   비급여 실비보험 · 비급여 실비청구 · 비급여 보험청구
 *   병원비 환급금 조회 · 신청 · 기간 · 지급일
 *
 * 전부 **개념과 절차**를 묻는 말이다. 금액 표로는 답할 수 없는 것이라
 * 그 검색어를 덮는 글을 따로 여기에 둔다.
 *
 * 본문은 컴포넌트로 따로 두고(app/[slug]/guides/) 여기서는 메타데이터만
 * 관리한다. 슬러그가 항목·지역·종별과 겹치지 않게 주의할 것. 적재
 * 스크립트(scripts/import-kosis.mjs)의 RESERVED 목록에도 같은 슬러그가
 * 들어 있어야 항목 이름이 이 글을 가리지 않는다.
 */

export interface Guide {
  slug: string;
  /** <h1> 과 검색 결과 제목 */
  title: string;
  /** 메타 설명. 130~160자 */
  description: string;
  /** 이 글이 덮으려는 검색어 */
  keywords: string[];
  /** 목록 화면에 쓰는 짧은 소개 */
  summary: string;
  emoji: string;
  /**
   * 본문의 h2 차례. 글머리에 목차로 싣는다.
   *
   * 본문은 컴포넌트에 있고 여기에는 제목만 둔다 — 본문에서 뽑아내려면
   * 렌더 결과를 뒤져야 하는데, 네 편뿐이라 손으로 맞추는 편이 단순하다.
   * **본문의 h2 id 와 글자 그대로 맞출 것.** 어긋나면 눌러도 움직이지 않는다.
   */
  outline: Array<{ id: string; label: string }>;
}

