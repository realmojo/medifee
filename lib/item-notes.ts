/**
 * 항목에 맞는 해설을 고른다.
 *
 * 이름 → 분류 → 계열 순으로 내려간다. 어느 항목도 빈손으로 돌려보내지 않는다.
 */
export function itemNote(item: {
  item_full_name: string;
  item_slug: string;
  category: string;
  fee_kind: string;
}): ItemNote {
  const haystack = `${item.item_full_name} ${item.item_slug} ${item.category}`;
  for (const rule of SPECIFIC) {
    if (rule.match.test(haystack)) return rule.note;
  }

  const byCategory = CATEGORY[item.category];
  if (byCategory && byCategory.what.length > 0) return byCategory;

  if (item.fee_kind === "certificate") return certificateNote();
  if (item.category.startsWith("처치 및 수술료")) return surgeryNote(item.category);
  if (item.category.startsWith("기능 검사료")) return functionTestNote(item.category);
  if (item.category.includes("초음파")) {
    const note = SPECIFIC.find((r) => r.match.source.includes("초음파"));
    if (note) return note.note;
  }
  if (item.category.includes("MRI")) {
    const note = SPECIFIC.find((r) => r.match.source.includes("MRI"));
    if (note) return note.note;
  }
  return treatmentNote();
}

/**
 * 이 항목을 찾을 때 쓰는 다른 말.
 *
 * 메타 키워드에 넣는다. 항목 이름 하나만 넣으면 "○○ 비용" 한 갈래만 덮는데,
 * 사람들은 "실비", "가격", "얼마"처럼 저마다 다른 말로 친다.
 */
export function noteKeywords(item: ItemStats, label: string): string[] {
  const note = itemNote(item);
  const base = [
    label,
    `${label} 비용`,
    `${label} 가격`,
    `${label} 실비`,
    `${label} 얼마`,
    `${label} 비급여`,
  ];
  return [...base, ...(note.aka ?? []), item.category, "비급여", "비급여 진료비"];
}

/** 값이 무엇 하나에 붙는지 한 마디로. 표 머리와 문장에 쓴다 */
export function cadenceWord(note: ItemNote): string | null {
  if (note.cadence === "session") return "1회당";
  if (note.cadence === "day") return "하루당";
  if (note.cadence === "piece") return "1개당";
  return null;
}
